//! The C++ output: the server side, as one header. For each `rpc_server` enum a
//! `constexpr` table to give the router; for each `rpc_service` method ids, a
//! `Handler` to implement, and a `Service` that adapts it to the router,
//! verifying requests. Messages are flatc's C++ tables, from the header named
//! by `--include`.

use std::collections::BTreeSet;
use std::fmt::Write as _;

use crate::backend::{Backend, live, snake};
use crate::schema::{Server, Service};

pub struct Cpp {
    /// The header `flatc --cpp` generated, as it's `#include`d.
    pub include: String,
}

