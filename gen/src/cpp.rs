/// An identifier that isn't a keyword.
fn ident(s: &str) -> String {
    if KEYWORDS.contains(&s) { format!("{s}_") } else { s.to_string() }
}

/// C++ path of a flatc-generated table, from the global namespace.
fn type_path(full: &str) -> String {
    format!("::{}", full.replace('.', "::"))
}

fn comment(out: &mut String, indent: &str, lines: &[String]) {
    for l in lines {
        writeln!(out, "{indent}//{l}").unwrap();
    }
}

/// The array of a service's methods that its server's table points to.
fn methods_array(service: &Service) -> String {
    format!("k{}Methods", service.full_name.replace('.', "_"))
}

impl Backend for Cpp {
    fn preamble(&self, out: &mut String, source: &str, _tables: &BTreeSet<&str>) {
        writeln!(
            out,
            "// @generated by tether-gen from {source}. Do not edit.
#pragma once

#include <array>
#include <cstddef>
#include <cstdint>
#include <optional>
#include <span>

#include \"{}\"
#include \"tether/descriptor.h\"
#include \"tether/router.h\"
#include \"tether/typed.h\"
",
            self.include
        )
        .unwrap();
    }

    fn open_namespace(&self, out: &mut String, namespace: &[String]) {
        if !namespace.is_empty() {
            writeln!(out, "namespace {} {{\n", namespace.join("::")).unwrap();
        }
    }

    fn close_namespace(&self, out: &mut String, namespace: &[String]) {
        if !namespace.is_empty() {
            writeln!(out, "}}  // namespace {}\n", namespace.join("::")).unwrap();
        }
    }

    fn server_table(&self, out: &mut String, server: &Server, services: &[Service]) {
        for service in server.slots.iter().flatten().map(|&i| &services[i]) {
            writeln!(
                out,
                "inline constexpr std::array<std::optional<tether::MethodInfo>, {}> {}{{",
                service.methods.len(),
                methods_array(service)
            )
            .unwrap();
            for m in &service.methods {
                if m.deprecated {
                    writeln!(out, "    std::nullopt,").unwrap();
                } else {
                    writeln!(
                        out,
                        "    tether::MethodInfo{{.name = {:?}, .streaming = {}}},",
                        m.name, m.streaming
                    )
                    .unwrap();
                }
            }
            writeln!(out, "}};\n").unwrap();
        }
        comment(out, "", &server.doc);
        writeln!(
            out,
            "inline constexpr std::array<std::optional<tether::ServiceInfo>, {}> k{}{{",
            server.slots.len(),
            server.name
        )
        .unwrap();
        for slot in &server.slots {
            match slot {
                None => writeln!(out, "    std::nullopt,").unwrap(),
                Some(i) => {
                    let s = &services[*i];
                    writeln!(
                        out,
                        "    tether::ServiceInfo{{.name = {:?}, .methods = {}}},",
                        s.full_name,
                        methods_array(s)
                    )
                    .unwrap();
                }
            }
        }
        writeln!(out, "}};\n").unwrap();
    }

    fn service(&self, out: &mut String, s: &Service) {
        comment(out, "", &s.doc);
        writeln!(
            out,
            "namespace {} {{

// This service's id in its server's table.
inline constexpr uint8_t kId = {};
",
            ident(&snake(&s.name)),
            s.id
        )
        .unwrap();
        for m in live(&s.methods) {
            writeln!(out, "// `{}`", m.full_name).unwrap();
            writeln!(out, "inline constexpr tether::MethodId k{}{{kId, {}}};", m.name, m.number)
                .unwrap();
        }

        writeln!(out, "\nclass Handler {{\n public:").unwrap();
        for m in live(&s.methods) {
            let (arg, ty) = if m.streaming { ("sink", "Sink") } else { ("reply", "Reply") };
            comment(out, "  ", &m.doc);
            writeln!(
                out,
                "  virtual void {}(tether::{ty}<{}> {arg}, const {}& request) = 0;",
                ident(&snake(&m.name)),
                type_path(&m.response),
                type_path(&m.request)
            )
            .unwrap();
        }
        writeln!(
            out,
            "  // The client dropped `call` before it finished.
  virtual void cancelled(tether::CallId /*call*/) {{}}

 protected:
  ~Handler() = default;
}};

class Service final : public tether::Service {{
 public:
  explicit Service(Handler& handler) : handler_(&handler) {{}}

  [[nodiscard]] uint8_t id() const override {{ return kId; }}
"
        )
        .unwrap();
        for streaming in [false, true] {
            let (signature, raw, wrap, reject) = if streaming {
                ("open", "tether::RawSink sink", "Sink", "sink.end")
            } else {
                ("call", "tether::RawReply reply", "Reply", "reply.fail")
            };
            let var = if streaming { "sink" } else { "reply" };
            writeln!(
                out,
                "  void {signature}([[maybe_unused]] uint8_t method,
            [[maybe_unused]] std::span<const std::byte> request,
            [[maybe_unused]] {raw}) override {{
    switch (method) {{"
            )
            .unwrap();
            for m in live(&s.methods).filter(|m| m.streaming == streaming) {
                writeln!(
                    out,
                    "      case {}: {{
        const auto* message = tether::verify<{}>(request);
        if (message == nullptr) {{
          (void){reject}(tether::WireStatus::INVALID_ARGUMENT);
          return;
        }}
        handler_->{}(tether::{wrap}<{}>({var}), *message);
        return;
      }}",
                    m.number,
                    type_path(&m.request),
                    ident(&snake(&m.name)),
                    type_path(&m.response)
                )
                .unwrap();
            }
            writeln!(
                out,
                "      default:
        (void){reject}(tether::WireStatus::UNIMPLEMENTED);
        return;
    }}
  }}
"
            )
            .unwrap();
        }
        writeln!(
            out,
            "  void cancelled(tether::CallId call) override {{ handler_->cancelled(call); }}

 private:
  Handler* handler_;
}};

}}  // namespace {}
",
            ident(&snake(&s.name))
        )
        .unwrap();
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::backend::generate;
    use crate::schema::fixtures::*;
    use crate::schema::{SchemaDef, resolve};

    fn code() -> String {
        let schema = SchemaDef {
            services: vec![service(
                "Wifi",
                vec![call("Connect", false), call("Scan", true), call("Delete", false)],
            )],
            servers: vec![server("Server", &[("Wifi", 0, false)])],
        };
        let r = resolve(&schema).unwrap();
        generate(&Cpp { include: "t_generated.h".into() }, &r, "test.fbs")
    }

    #[test]
    fn a_tombstone_keeps_its_number_and_has_no_handler() {
        let code = code();
        assert!(code.contains("inline constexpr tether::MethodId kDelete{kId, 2};"), "{code}");
        assert!(!code.contains("kScan") && !code.contains(" scan("), "{code}");
        assert!(
            code.contains("    std::nullopt,\n    tether::MethodInfo{.name = \"Delete\""),
            "{code}"
        );
    }

    #[test]
    fn keywords_are_not_identifiers() {
        let code = code();
        assert!(code.contains("virtual void delete_("), "{code}");
        assert!(code.contains("handler_->delete_("), "{code}");
    }

    #[test]
    fn requests_are_verified_and_answered_invalid_argument() {
        let code = code();
        assert!(code.contains("tether::verify<::T::Req>(request)"), "{code}");
        assert!(
            code.contains("(void)reply.fail(tether::WireStatus::INVALID_ARGUMENT)"),
            "{code}"
        );
    }

    #[test]
    fn the_namespaces_follow_the_schema() {
        let code = code();
        assert!(code.contains("namespace T {"), "{code}");
        assert!(code.contains("namespace wifi {"), "{code}");
        assert!(
            code.contains(
                "inline constexpr std::array<std::optional<tether::ServiceInfo>, 1> kServer{"
            ),
            "{code}"
        );
    }
}
