//! The Rust output: typed clients, handler traits and services on the `tether`
//! crate, over the types `flatc --rust --gen-object-api` generated.

use std::collections::BTreeSet;
use std::fmt::Write as _;

use crate::backend::{Backend, live, snake};
use crate::schema::{Server, Service};

pub struct Rust {
    /// Path of `flatc --rust --gen-object-api` output in the generated code.
    pub types: String,
    /// Path of the `tether` crate in the generated code.
    pub tether: String,
}

impl Backend for Rust {
    fn preamble(&self, out: &mut String, source: &str, tables: &BTreeSet<&str>) {
        let tether = &self.tether;
        writeln!(out, "// @generated by tether-gen from {source}. Do not edit.").unwrap();
        writeln!(out, "#![allow(clippy::all, unused_imports, unused_variables)]\n").unwrap();
        writeln!(out, "use {tether}::flatbuffers;").unwrap();
        writeln!(out, "use {tether}::{{Pack, Table}};").unwrap();
        writeln!(out, "use alloc::vec::Vec;").unwrap();
        writeln!(out, "use {} as fb;\n", self.types).unwrap();
        for t in tables {
            let p = type_path(t);
            writeln!(
                out,
                "impl Table for {p}<'static> {{
    type View<'a> = {p}<'a>;
    fn verify(buf: &[u8]) -> Result<{p}<'_>, flatbuffers::InvalidFlatbuffer> {{
        flatbuffers::root::<{p}>(buf)
    }}
}}

impl Pack for {p}T {{
    fn to_bytes(&self) -> Vec<u8> {{
        let mut fbb = flatbuffers::FlatBufferBuilder::new();
        let root = self.pack(&mut fbb);
        fbb.finish(root, None);
        fbb.finished_data().to_vec()
    }}
}}
"
            )
            .unwrap();
        }
    }

    fn open_namespace(&self, out: &mut String, namespace: &[String]) {
        for n in namespace {
            writeln!(out, "pub mod {} {{", snake(n)).unwrap();
        }
    }

    fn close_namespace(&self, out: &mut String, namespace: &[String]) {
        for _ in namespace {
            writeln!(out, "}}").unwrap();
        }
    }

    fn server_table(&self, out: &mut String, server: &Server, services: &[Service]) {
        server_table(out, server, services, &self.tether);
    }

    fn service(&self, out: &mut String, service: &Service) {
        service_code(out, service, &self.tether, &self.types);
    }
}

// --- Rust output ---

fn ident(s: &str) -> String {
    const KEYWORDS: &[&str] = &[
        "as", "async", "await", "box", "break", "const", "continue", "crate", "dyn", "else",
        "enum", "extern", "fn", "for", "gen", "if", "impl", "in", "let", "loop", "match", "mod",
        "move", "mut", "pub", "ref", "return", "static", "struct", "trait", "type", "unsafe",
        "use", "where", "while", "yield",
    ];
    if KEYWORDS.contains(&s) { format!("r#{s}") } else { s.to_string() }
}

/// Rust path of a flatc-generated table, e.g. `fb::coprocessor_proto::WifiStatus`.
fn type_path(full: &str) -> String {
    let mut parts: Vec<String> = full.split('.').map(str::to_string).collect();
    let name = parts.pop().unwrap();
    let mut path = String::from("fb");
    for p in parts {
        path += "::";
        path += &snake(&p);
    }
    path + "::" + &name
}

fn doc(out: &mut String, indent: &str, lines: &[String]) {
    for l in lines {
        writeln!(out, "{indent}///{l}").unwrap();
    }
}

fn server_table(out: &mut String, srv: &Server, services: &[Service], tether: &str) {
    doc(out, "", &srv.doc);
    let name = snake(&srv.name).to_uppercase();
    writeln!(out, "pub static {name}: &{tether}::ServerTable = &[").unwrap();
    for slot in &srv.slots {
        let Some(i) = slot else {
            writeln!(out, "    None,").unwrap();
            continue;
        };
        let s = &services[*i];
        writeln!(out, "    Some({tether}::ServiceInfo {{ name: {:?}, methods: &[", s.full_name)
            .unwrap();
        for m in &s.methods {
            if m.deprecated {
                writeln!(out, "        None,").unwrap();
            } else {
                writeln!(
                    out,
                    "        Some({tether}::MethodInfo {{ name: {:?}, streaming: {} }}),",
                    m.name, m.streaming
                )
                .unwrap();
            }
        }
        writeln!(out, "    ] }}),").unwrap();
    }
    writeln!(out, "];\n").unwrap();
}

fn service_code(out: &mut String, s: &Service, tether: &str, types: &str) {
    doc(out, "", &s.doc);
    writeln!(
        out,
        "pub mod {} {{
    use {tether}::flatbuffers;
    use {tether}::{{
        Call, CallId, Channel, MethodId, Pack, RawReply, RawSink, Reply, ServerTypes, Sink, Status,
        Transport,
    }};

    use {types} as fb;

    /// This service's id in its server's table.
    pub const ID: u8 = {};
",
        snake(&s.name),
        s.id
    )
    .unwrap();
    for m in live(&s.methods) {
        writeln!(out, "    /// `{}`", m.full_name).unwrap();
        let konst = snake(&m.name).to_uppercase();
        writeln!(out, "    pub const {konst}: MethodId = MethodId::new(ID, {});", m.number)
            .unwrap();
    }

    writeln!(out, "\n    pub struct Client<X>(pub X);\n").unwrap();
    writeln!(out, "    impl<X: Transport> Client<X> {{").unwrap();
    for m in live(&s.methods) {
        let (fn_name, konst) = (ident(&snake(&m.name)), snake(&m.name).to_uppercase());
        let (req, resp) = (type_path(&m.request), type_path(&m.response));
        doc(out, "        ", &m.doc);
        if m.streaming {
            writeln!(
                out,
                "        pub fn {fn_name}(&self, req: &{req}T, capacity: u16) -> Channel<X::Channel, {resp}<'static>> {{
            Channel::new(self.0.open({konst}, &req.to_bytes(), capacity))
        }}"
            )
            .unwrap();
        } else {
            writeln!(
                out,
                "        pub fn {fn_name}(&self, req: &{req}T) -> Call<X::Call, {resp}<'static>> {{
            Call::new(self.0.call({konst}, &req.to_bytes(), {}))
        }}",
                m.timeout_ms
            )
            .unwrap();
        }
    }
    writeln!(out, "    }}\n").unwrap();

    writeln!(out, "    pub trait Handler<S: ServerTypes> {{").unwrap();
    for m in live(&s.methods) {
        let fn_name = ident(&snake(&m.name));
        let (req, resp) = (type_path(&m.request), type_path(&m.response));
        let (arg, ty) =
            if m.streaming { ("sink", "Sink<S::Sink") } else { ("reply", "Reply<S::Reply") };
        doc(out, "        ", &m.doc);
        writeln!(out, "        fn {fn_name}(&mut self, {arg}: {ty}, {resp}T>, req: {req}<'_>);")
            .unwrap();
    }
    writeln!(
        out,
        "        /// The client dropped `call` before it finished.
        fn cancelled(&mut self, _call: CallId) {{}}
    }}

    pub struct Service<H>(pub H);

    impl<S: ServerTypes, H: Handler<S>> {tether}::Service<S> for Service<H> {{
        fn id(&self) -> u8 {{
            ID
        }}
"
    )
    .unwrap();
    for streaming in [false, true] {
        let (signature, wrap, reject) = if streaming {
            (
                "open(&mut self, method: u8, request: &[u8], sink: S::Sink)",
                "Sink::new(sink)",
                "sink.end",
            )
        } else {
            (
                "call(&mut self, method: u8, request: &[u8], reply: S::Reply)",
                "Reply::new(reply)",
                "reply.send",
            )
        };
        writeln!(out, "        fn {signature} {{\n            match method {{").unwrap();
        for m in live(&s.methods).filter(|m| m.streaming == streaming) {
            let (fn_name, req) = (ident(&snake(&m.name)), type_path(&m.request));
            writeln!(
                out,
                "                {} => match flatbuffers::root::<{req}>(request) {{
                    Ok(req) => self.0.{fn_name}({wrap}, req),
                    Err(_) => {reject}(Err(Status::InvalidArgument)),
                }},",
                m.number
            )
            .unwrap();
        }
        writeln!(
            out,
            "                _ => {reject}(Err(Status::Unimplemented)),\n            }}\n        }}\n"
        )
        .unwrap();
    }
    writeln!(
        out,
        "        fn cancelled(&mut self, call: CallId) {{
            self.0.cancelled(call)
        }}
    }}
}}
"
    )
    .unwrap();
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::backend::generate;
    use crate::schema::fixtures::*;
    use crate::schema::{SchemaDef, resolve};

    #[test]
    fn deprecated_method_keeps_its_number() {
        let calls = vec![call("Connect", false), call("Scan", true), call("Watch", false)];
        let schema = SchemaDef {
            services: vec![service("Wifi", calls)],
            servers: vec![server("Server", &[("Wifi", 0, false)])],
        };
        let r = resolve(&schema).unwrap();
        let numbers: Vec<_> =
            r.services[0].methods.iter().map(|m| (m.number, m.deprecated)).collect();
        assert_eq!(numbers, [(0, false), (1, true), (2, false)]);

        let backend = Rust { types: "t".into(), tether: "tether".into() };
        let code = generate(&backend, &r, "test");
        assert!(code.contains("pub const WATCH: MethodId = MethodId::new(ID, 2);"), "{code}");
        assert!(!code.contains("SCAN") && !code.contains("fn scan"), "{code}");
    }
}
